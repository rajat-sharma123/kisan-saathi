export function getTranslation(langCode = 'hi') {
  const current = TRANSLATIONS[langCode] || TRANSLATIONS.hi;
  const fallback = TRANSLATIONS.hi;
  const english = TRANSLATIONS.en;

  return new Proxy(current, {
    get(target, prop) {
      if (prop in target && target[prop] !== undefined && target[prop] !== '') {
        return target[prop];
      }
      if (prop in fallback && fallback[prop] !== undefined && fallback[prop] !== '') {
        return fallback[prop];
      }
      if (prop in english && english[prop] !== undefined && english[prop] !== '') {
        return english[prop];
      }
      return '';
    }
  });
}
